/** ✅ دسته‌های یک آیتم بر اساس گروهش؛ آیتم‌های چندگروهی همهٔ دسته‌ها را می‌گیرند */
export function categoriesOf(group: string): string[] {
  if (!group) return [];
  const whole = GROUP_MAP[group];
  if (whole) return whole;
  // تلاش با تفکیک '/'
  const out = new Set<string>();
  group.split('/').map((s) => s.trim()).forEach((t) => {
    (GROUP_MAP[t] ?? []).forEach((c) => out.add(c));
  });
  if (out.size === 0 && CATEGORIES.includes(group)) out.add(group);
  return Array.from(out);
}